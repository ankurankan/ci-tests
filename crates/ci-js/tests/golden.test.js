// Golden parity test for the data-bound JavaScript / WebAssembly bindings.
//
// Loads the shared cross-language fixture `tests/fixtures/golden.json` (at the
// repository root) and, for each of the twelve tests, builds a `Dataset` from the
// case's columns, constructs the test with the case's parameters, runs it, and
// asserts that `statistic` / `pValue` / `dof` / `effectSize` match the recorded
// `expected` values within 1e-7 (hsic/kci/gcm/pillai cases carry a `rel_tol` and use a relative
// tolerance instead). This is the binding's numeric parity gate
// against the scipy/pgmpy reference, mirroring the Rust
// (`crates/ci-core/tests/golden.rs`) and Python
// (`crates/ci-python/test/test_golden.py`) gates.

import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { describe, test, expect, beforeAll } from "vitest";

// The wasm package is generated by `wasm-pack build crates/ci-js --target nodejs`
// into `crates/ci-js/pkg`. It is a CommonJS module; default-import then
// destructure so the named classes resolve regardless of interop quirks.
import pkg from "../pkg/fastcit.js";
const {
  Dataset,
  ChiSquared,
  LogLikelihood,
  CressieRead,
  FreemanTukey,
  ModifiedLikelihood,
  PearsonCorrelation,
  PearsonEquivalence,
  FisherZ,
  HSIC,
  KCI,
  GCM,
  PillaiTrace,
  init,
} = pkg;

const TOL = 1e-7;

// Map the fixture's stable test name to its binding class.
const TEST_CLASSES = {
  chi_squared: ChiSquared,
  log_likelihood: LogLikelihood,
  cressie_read: CressieRead,
  freeman_tukey: FreemanTukey,
  modified_likelihood: ModifiedLikelihood,
  pearson_correlation: PearsonCorrelation,
  pearson_equivalence: PearsonEquivalence,
  fisher_z: FisherZ,
  hsic: HSIC,
  kci: KCI,
  gcm: GCM,
  pillai: PillaiTrace,
};

const __dirname = dirname(fileURLToPath(import.meta.url));
// crates/ci-js/tests/golden.test.js -> repo root is three parents up.
const GOLDEN_PATH = resolve(
  __dirname,
  "..",
  "..",
  "..",
  "tests",
  "fixtures",
  "golden.json",
);

const GOLDEN_CASES = JSON.parse(readFileSync(GOLDEN_PATH, "utf8"));

beforeAll(() => {
  // Install the panic hook so any Rust panic surfaces as a readable JS error.
  init();
});

/** Build a `Dataset` wasm object from a fixture case's `columns`. */
function buildDataset(columns) {
  const spec = {};
  for (const [name, col] of Object.entries(columns)) {
    spec[name] = { kind: col.kind, values: col.values };
  }
  return new Dataset(spec);
}

/** Map a fixture kernel JSON object to the binding's `KernelSpec`. */
function kernelSpec(k) {
  return k.type === "rbf"
    ? { type: "rbf", lengthScale: k.length_scale }
    : { type: "linear" };
}

/** Construct the test class for `name`, bound to `data`, with the case params. */
function construct(name, data, params) {
  const cls = TEST_CLASSES[name];
  const options = {};
  for (const [key, value] of Object.entries(params)) {
    if (value === null || value === undefined) continue;
    if (key === "delta_threshold") options.deltaThreshold = value;
    else if (key === "null_dist") options.nullDist = value;
    else if (key === "n_permutations") options.nPermutations = value;
    else if (key === "kernel") {
      if (value.columns) {
        options.kernels = Object.fromEntries(
          Object.entries(value.columns).map(([c, k]) => [c, kernelSpec(k)]),
        );
      } else {
        options.kernel = kernelSpec(value);
      }
    } else options[key] = value;
  }
  return new cls(data, options);
}

/**
 * Assert `actual` matches `expected` for `field` within TOL (or `relTol` relative, when given). Null/undefined
 * expectations require an absent result. Infinity / NaN are handled exactly
 * (none appear in the current fixture, but be defensive).
 */
function assertClose(actual, expected, field, caseId, relTol = null) {
  if (expected === null || expected === undefined) {
    expect(
      actual === null || actual === undefined,
      `${caseId}: expected ${field}=null, got ${actual}`,
    ).toBe(true);
    return;
  }
  expect(
    actual,
    `${caseId}: expected ${field}=${expected}, got ${actual}`,
  ).not.toBeNull();
  expect(actual, `${caseId}: ${field} should be defined`).not.toBeUndefined();

  const exp = Number(expected);
  if (!Number.isFinite(exp)) {
    // Infinite or NaN expectation: require an exactly-matching actual.
    if (Number.isNaN(exp)) {
      expect(Number.isNaN(actual), `${caseId}: ${field} expected NaN`).toBe(
        true,
      );
    } else {
      expect(actual, `${caseId}: ${field} expected ${exp}`).toBe(exp);
    }
    return;
  }
  const bound =
    relTol === null ? TOL : Math.max(1e-300, relTol * Math.abs(exp));
  expect(
    Math.abs(actual - exp),
    `${caseId}: ${field} mismatch: got ${actual}, expected ${exp}`,
  ).toBeLessThanOrEqual(bound);
}

describe("golden fixture parity", () => {
  const counts = {};

  test.each(GOLDEN_CASES.map((c) => [c.id, c]))(
    "%s",
    (_fixtureCaseId, testCase) => {
      const caseId = testCase.id;
      expect(caseId, "fixture case ID must not be empty").not.toBe("");
      expect(TEST_CLASSES, `${caseId}: unknown test name`).toHaveProperty(
        testCase.test,
      );

      const data = buildDataset(testCase.columns);
      const test_ = construct(testCase.test, data, testCase.params);
      const result = test_.runTest(testCase.x, testCase.y, testCase.z);
      const expected = testCase.expected;
      const relTol = testCase.rel_tol ?? null;

      assertClose(
        result.statistic,
        expected.statistic,
        "statistic",
        caseId,
        relTol,
      );

      assertClose(result.pValue, expected.p_value, "pValue", caseId, relTol);

      assertClose(
        result.dof,
        expected.dof === null || expected.dof === undefined
          ? expected.dof
          : Number(expected.dof),
        "dof",
        caseId,
      );
      assertClose(
        result.effectSize,
        expected.effect_size,
        "effectSize",
        caseId,
      );

      counts[testCase.test] = (counts[testCase.test] ?? 0) + 1;
    },
  );

  test("all fixture cases were exercised", () => {
    const total = Object.values(counts).reduce((sum, count) => sum + count, 0);
    expect(total).toBe(GOLDEN_CASES.length);
    expect(new Set(Object.keys(counts))).toEqual(
      new Set(Object.keys(TEST_CLASSES)),
    );
  });
});
